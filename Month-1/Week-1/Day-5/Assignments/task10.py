# Create a list of numbers and:
# 1. Add one number using append()
# 2. Add one number using insert()

numbers = [10, 20, 30, 40]
print("Original list:", numbers)

# Adding 50 to the end
numbers.append(50)
print("After append(50):", numbers)

# Inserting 15 at index 1
numbers.insert(1, 15)
print("After insert(1, 15):", numbers)
